    namespace ncc\Classes;

    use Random\RandomException;

    /**
     * Composer runtime compatibility for packages converted from Composer projects.
     *
     * Composer bin scripts (phpunit, php-cs-fixer, phpstan, ...) expect a real `vendor/autoload.php` on disk; Composer's
     * bin proxies hand it to them through `$GLOBALS['_composer_autoload_path']`. Some of these tools also pass that
     * path to child PHP processes (PHPUnit's process isolation and PHPT runner), which start without ncc loaded.
     * The autoload shim is a real file that loads ncc and imports the package, so it works in both places.
     */
    class ComposerCompat
    {
        public const string AUTOLOAD_SHIM_SUFFIX = '.autoload.php';
        public const string AUTOLOAD_SHIM_MARKER = '// NCC_COMPOSER_AUTOLOAD_SHIM';

        /**
         * Returns the path of an up-to-date autoload shim for the given package, writing it if it is missing or stale.
         *
         * The shim is written next to the package file when possible, otherwise to a per-user temporary directory.
         *
         * @param string $packagePath The absolute path to the package file
         * @param string $packageName The package name (eg; com.phpunit.phpunit)
         * @return string|null The absolute path to the shim, or null if it could not be written anywhere
         */
        public static function getAutoloadShim(string $packagePath, string $packageName): ?string
        {
            $content = self::generateAutoloadShim($packagePath, $packageName);
            if($content === null)
            {
                return null;
            }

            foreach([self::getInstalledShimPath($packagePath), self::getTemporaryShimPath($packagePath)] as $shimPath)
            {
                if($shimPath !== null && self::writeShim($shimPath, $content))
                {
                    return $shimPath;
                }
            }

            Logger::getLogger()?->warning(sprintf('Could not write a Composer autoload shim for %s', $packageName));
            return null;
        }

        /**
         * Returns the path of the autoload shim that belongs next to an installed package file
         *
         * @param string $packagePath The path to the package file
         * @return string The shim path
         */
        public static function getInstalledShimPath(string $packagePath): string
        {
            return $packagePath . self::AUTOLOAD_SHIM_SUFFIX;
        }

        /**
         * Generates the PHP source of the autoload shim for a package
         *
         * @param string $packagePath The absolute path to the package file
         * @param string $packageName The package name
         * @return string|null The shim source, or null if ncc's own location is unknown
         */
        public static function generateAutoloadShim(string $packagePath, string $packageName): ?string
        {
            if(!defined('__NCC_DIR__'))
            {
                return null;
            }

            $nccPath = var_export(__NCC_DIR__ . DIRECTORY_SEPARATOR . 'ncc.php', true);
            $exportedPackagePath = var_export($packagePath, true);
            $exportedPackageName = var_export($packageName, true);
            $marker = self::AUTOLOAD_SHIM_MARKER;

            return <<<PHP
<?php
{$marker}
// Composer autoload shim for {$packageName}, generated by ncc. Do not edit.
// It loads ncc and imports the package so Composer tools work here and in child PHP processes.

if(!defined('__NCC__'))
{
    require {$nccPath};
}

if(!\\ncc\\Runtime::isImported({$exportedPackageName}))
{
    \\ncc\\Runtime::import({$exportedPackagePath});
}

return true;

PHP;
        }

        /**
         * Exposes the Composer runtime globals that bin scripts expect, returning the previous values so they can be
         * restored with restoreGlobals()
         *
         * @param string $scriptPath The path of the script being executed
         * @param string[] $arguments The arguments passed to the script
         * @param string|null $autoloadShimPath The autoload shim to expose, null to leave the Composer global untouched
         * @return array The previous state of the modified globals
         */
        public static function applyGlobals(string $scriptPath, array $arguments, ?string $autoloadShimPath): array
        {
            $previous = [];
            $values = [
                'argv' => array_merge([$scriptPath], array_values($arguments)),
            ];
            $values['argc'] = count($values['argv']);

            if($autoloadShimPath !== null)
            {
                $values['_composer_autoload_path'] = $autoloadShimPath;
            }

            foreach($values as $key => $value)
            {
                $previous[$key] = array_key_exists($key, $GLOBALS) ? ['set' => true, 'value' => $GLOBALS[$key]] : ['set' => false];
                $GLOBALS[$key] = $value;
            }

            $previous['_server'] = [
                'argv' => $_SERVER['argv'] ?? null,
                'argc' => $_SERVER['argc'] ?? null,
            ];
            $_SERVER['argv'] = $values['argv'];
            $_SERVER['argc'] = $values['argc'];

            return $previous;
        }

        /**
         * Restores the globals modified by applyGlobals()
         *
         * @param array $previous The state returned by applyGlobals()
         * @return void
         */
        public static function restoreGlobals(array $previous): void
        {
            foreach($previous['_server'] ?? [] as $key => $value)
            {
                if($value === null)
                {
                    unset($_SERVER[$key]);
                }
                else
                {
                    $_SERVER[$key] = $value;
                }
            }
            unset($previous['_server']);

            foreach($previous as $key => $state)
            {
                if($state['set'])
                {
                    $GLOBALS[$key] = $state['value'];
                }
                else
                {
                    unset($GLOBALS[$key]);
                }
            }
        }

        /**
         * Registers a last-resort autoloader providing Composer\InstalledVersions backed by ncc. Calling it again moves
         * it behind autoloaders registered since, so a package or real Composer installation that provides the class
         * always wins.
         *
         * @return void
         */
        public static function registerInstalledVersionsFallback(): void
        {
            static $fallback = null;
            if($fallback === null)
            {
                $fallback = static function(string $className): void
                {
                    if(strcasecmp($className, 'Composer\\InstalledVersions') === 0)
                    {
                        // .inc so ncc's own generated autoloader never claims the class over a real Composer installation
                        require_once __DIR__ . DIRECTORY_SEPARATOR . '..' . DIRECTORY_SEPARATOR . 'Compat' . DIRECTORY_SEPARATOR . 'Composer' . DIRECTORY_SEPARATOR . 'InstalledVersions.inc';
                    }
                };
            }
            else
            {
                spl_autoload_unregister($fallback);
            }

            spl_autoload_register($fallback);
        }

        /**
         * Returns the per-user temporary shim path for a package, used when the package directory is not writable
         *
         * @param string $packagePath The path to the package file
         * @return string|null The temporary shim path, or null if the temporary directory cannot be used
         */
        private static function getTemporaryShimPath(string $packagePath): ?string
        {
            $user = function_exists('posix_geteuid') ? (string)posix_geteuid() : preg_replace('/[^A-Za-z0-9_.-]/', '_', get_current_user());
            $directory = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'ncc-composer-' . $user;

            if(!is_dir($directory) && !@mkdir($directory, 0700, true) && !is_dir($directory))
            {
                return null;
            }

            return $directory . DIRECTORY_SEPARATOR . sha1($packagePath) . '.php';
        }

        /**
         * Writes the shim if its content differs, replacing it atomically so concurrent readers never see a partial file
         *
         * @param string $shimPath The path to write the shim to
         * @param string $content The shim content
         * @return bool True if the shim is in place with the given content
         */
        private static function writeShim(string $shimPath, string $content): bool
        {
            if(is_file($shimPath) && @file_get_contents($shimPath) === $content)
            {
                return true;
            }

            // Never overwrite a file that isn't ours
            if(file_exists($shimPath) && !str_contains((string)@file_get_contents($shimPath, false, null, 0, 256), self::AUTOLOAD_SHIM_MARKER))
            {
                return false;
            }

            $directory = dirname($shimPath);
            if(!is_dir($directory) || !is_writable($directory))
            {
                return false;
            }

            try
            {
                $temporaryPath = $shimPath . '.' . bin2hex(random_bytes(4)) . '.tmp';
            }
            catch (RandomException $e)
            {
                throw new \RuntimeException('Unable to generate random bytes', $e->getCode(), $e);
            }
            if(@file_put_contents($temporaryPath, $content) === false)
            {
                return false;
            }

            @chmod($temporaryPath, 0644);
            if(!@rename($temporaryPath, $shimPath))
            {
                @unlink($temporaryPath);
                return false;
            }

            Logger::getLogger()?->verbose(sprintf('Wrote Composer autoload shim: %s', $shimPath));
            return true;
        }
    }
